import express from 'express';
import { store } from '../db/store.js';
import { authenticateToken } from '../middleware/auth.js';

const router = express.Router();

// GET /api/analytics/overview (Full predictive analytics data payload)
router.get('/overview', authenticateToken, (req, res) => {
  const historical = store.analyticsHistorical || {
    weeklyAdmissions: [],
    next7DaysForecast: [],
    resourceUtilization: {}
  };

  // Compute live metrics from store
  const totalPatients = store.users.filter(u => u.role === 'Patient').length;
  const totalTriageActive = (store.triageQueue || []).filter(t => t.status === 'Active ER Queue').length;
  const criticalTriageCount = (store.triageQueue || []).filter(t => t.priorityResult?.priority === 'Critical').length;
  const lowBloodUnitsCount = (store.bloodInventory || []).filter(b => b.units <= b.minThreshold).length;
  const lowStockMedsCount = (store.medicines || []).filter(m => m.stock <= m.reorderLevel).length;

  // Medicine burn rate / days to depletion calculation
  const medicineBurnProjections = (store.medicines || []).slice(0, 6).map(m => {
    // Simulated daily burn rate based on category and reorder level
    const dailyBurnRate = Math.max(3, Math.round(m.reorderLevel / 7));
    const daysUntilStockout = Math.max(1, Math.round(m.stock / dailyBurnRate));
    return {
      medicineId: m.id,
      name: m.name,
      category: m.category,
      currentStock: m.stock,
      dailyBurnRate,
      daysUntilStockout,
      urgency: daysUntilStockout <= 5 ? 'High Urgency' : daysUntilStockout <= 12 ? 'Moderate' : 'Stable'
    };
  });

  // Blood group stock vs projected 7-day requirement
  const bloodProjections = (store.bloodInventory || []).map(b => {
    const projected7DayDemand = Math.round(b.minThreshold * 1.8);
    const deficit = projected7DayDemand - b.units;
    return {
      bloodGroup: b.bloodGroup,
      currentUnits: b.units,
      projected7DayDemand,
      projectedStatus: deficit > 0 ? `Deficit (-${deficit} units)` : `Adequate (+${Math.abs(deficit)} units)`,
      alertRequired: deficit > 0
    };
  });

  // Bed & resource utilization
  const resUtil = historical.resourceUtilization || {
    totalGeneralBeds: 250,
    occupiedGeneralBeds: 205,
    totalIcuBeds: 45,
    occupiedIcuBeds: 40,
    totalVentilators: 20,
    occupiedVentilators: 15,
    activeDoctorsOnDuty: 28,
    ambulancesOperational: 8,
    ambulancesDispatched: 5
  };

  const generalBedRate = Math.round((resUtil.occupiedGeneralBeds / resUtil.totalGeneralBeds) * 100);
  const icuBedRate = Math.round((resUtil.occupiedIcuBeds / resUtil.totalIcuBeds) * 100);
  const ventilatorRate = Math.round((resUtil.occupiedVentilators / resUtil.totalVentilators) * 100);

  // AI-generated prescriptive insights
  const aiRecommendations = [
    {
      id: 'rec_ai_1',
      priority: 'High',
      department: 'Intensive Care Unit (ICU)',
      message: `ICU occupancy is at ${icuBedRate}% (40/45 beds). Predictive engine estimates threshold saturation in 16 hours. Recommended: Expedite step-down transfers to High Dependency Unit (HDU).`,
      action: 'Trigger ICU De-escalation Protocol'
    },
    {
      id: 'rec_ai_2',
      priority: 'High',
      department: 'Pharmacy & Medical Supplies',
      message: `${lowStockMedsCount} critical pharmaceuticals are below reorder threshold. Epinephrine auto-injectors and Albuterol inhalers have fewer than 5 days supply at current burn rates.`,
      action: 'Initiate Urgent Batch Restock'
    },
    {
      id: 'rec_ai_3',
      priority: 'Medium',
      department: 'Blood Bank & Donor Dispatch',
      message: `Projected 7-day deficit detected for O- and B- blood units. Urgent donor matching notifications recommended for registered donors within 5 km radius.`,
      action: 'Broadcast Donor Notification'
    },
    {
      id: 'rec_ai_4',
      priority: 'Medium',
      department: 'Emergency & Triage Department',
      message: 'Predicted Friday/Saturday patient influx surge of +28% due to seasonal meteorological shift. Schedule 3 additional on-call triage physicians.',
      action: 'Roster Additional Staff'
    }
  ];

  res.json({
    timestamp: new Date().toISOString(),
    advisoryDisclaimer: 'Clinical Advisory Notice: All predictive analytics outputs, risk scorings, and forecasts are statistical analytical estimates generated by the MediNova Predictive Engine for operational and clinical decision support. They do not constitute guaranteed outcomes or replace clinical professional medical judgement.',
    liveStats: {
      totalPatients,
      totalTriageActive,
      criticalTriageCount,
      lowBloodUnitsCount,
      lowStockMedsCount
    },
    historicalAdmissions: historical.weeklyAdmissions,
    next7DaysForecast: historical.next7DaysForecast,
    resourceUtilization: {
      ...resUtil,
      generalBedRate,
      icuBedRate,
      ventilatorRate
    },
    medicineBurnProjections,
    bloodProjections,
    aiRecommendations
  });
});

// POST /api/analytics/simulate (Scenario Simulation Engine)
router.post('/simulate', authenticateToken, (req, res) => {
  const { scenarioType, surgeMultiplier = 1.3, durationDays = 7 } = req.body;

  const baseOccupiedBeds = store.analyticsHistorical?.resourceUtilization?.occupiedGeneralBeds || 205;
  const totalBeds = store.analyticsHistorical?.resourceUtilization?.totalGeneralBeds || 250;
  const baseIcu = store.analyticsHistorical?.resourceUtilization?.occupiedIcuBeds || 40;
  const totalIcu = store.analyticsHistorical?.resourceUtilization?.totalIcuBeds || 45;

  const simulatedBedDemand = Math.round(baseOccupiedBeds * surgeMultiplier);
  const simulatedIcuDemand = Math.round(baseIcu * (surgeMultiplier * 1.1));
  const bedShortage = Math.max(0, simulatedBedDemand - totalBeds);
  const icuShortage = Math.max(0, simulatedIcuDemand - totalIcu);

  res.json({
    scenario: scenarioType || 'Custom Surge Simulation',
    surgeMultiplier,
    durationDays,
    impact: {
      projectedBedDemand: simulatedBedDemand,
      bedCapacity: totalBeds,
      bedDeficit: bedShortage,
      bedSaturationRate: Math.min(100, Math.round((simulatedBedDemand / totalBeds) * 100)),
      projectedIcuDemand: simulatedIcuDemand,
      icuCapacity: totalIcu,
      icuDeficit: icuShortage,
      icuSaturationRate: Math.min(100, Math.round((simulatedIcuDemand / totalIcu) * 100)),
      estimatedAdditionalAmbulancesNeeded: Math.ceil(surgeMultiplier * 3),
      recommendation: bedShortage > 0 || icuShortage > 0
        ? `CRITICAL BOTTLENECK DETECTED: This scenario exceeds maximum facility bed/ICU capacity by ${bedShortage + icuShortage} units. Recommend mutual aid coordination with adjacent regional hospitals.`
        : 'MANAGEABLE LOAD: Current facility resources can absorb this surge with existing auxiliary reserves.'
    }
  });
});

export default router;
